function getHomeFaq(city: City) {
  const cityQuestion = city.custom?.homeIntro
    ? { q: `Как вы работаете в ${city.prepositionalName}?`, a: city.custom.homeIntro }
    : {
        q: "В каких городах вы работаете?",
        a: "Работаем в Москве и большинстве крупных городов Московской области. Полный список городов — на странице «Города».",
      };

  // A stable per-city index (not a hash) guarantees each city gets a distinct FAQ variant as
  // long as each pool is at least as large as the number of active cities — a hash-based pick
  // only randomizes which cities collide, it doesn't prevent collisions outright.
  const sortedSlugs = getActiveCities()
    .map((c) => c.slug)
    .sort();
  const index = Math.max(0, sortedSlugs.indexOf(city.slug));

  const priceQuestion = PRICE_FAQ_VARIANTS[index % PRICE_FAQ_VARIANTS.length];
  const hoursQuestion = HOURS_FAQ_VARIANTS[index % HOURS_FAQ_VARIANTS.length];
  const separateServiceQuestion = SEPARATE_SERVICE_FAQ_VARIANTS[index % SEPARATE_SERVICE_FAQ_VARIANTS.length];

  return [cityQuestion, priceQuestion, hoursQuestion, separateServiceQuestion];
}

